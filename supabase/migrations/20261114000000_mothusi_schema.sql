-- Mothusi: the full database schema.
-- The backend creates the same tables with CREATE TABLE IF NOT EXISTS when it starts, so this migration and the
-- code always agree. Supabase is used as a PostgreSQL database only: accounts, sessions and uploaded files are
-- handled by the Mothusi backend, which connects as the database owner.
--
-- Row-level security is enabled on every table with no policies, so Supabase's public API (the anon and
-- authenticated keys) cannot read or write any of this data. Only the backend can.

-- ---------------------------------------------------------------- accounts and sign-in

create table if not exists accounts (
    id text primary key,
    email text not null unique,              -- stored in lower case
    role text not null check (role in ('learner', 'teacher')),
    password_hash text not null,             -- PBKDF2-SHA256
    profile_json text not null,
    created_at text not null
);

create table if not exists auth_sessions (
    token_hash text primary key,             -- SHA-256 of the session token; the token itself is never stored
    account_id text not null references accounts(id) on delete cascade,
    expires_at text not null,
    created_at text not null
);
create index if not exists auth_sessions_account on auth_sessions (account_id);

create table if not exists join_codes (
    code text primary key,
    teacher_id text not null references accounts(id) on delete cascade,
    class_id text not null,
    class_name text not null,
    learner_profile_id text,
    learner_label text,
    created_at text not null,
    revoked_at text,
    claimed_by text,
    claimed_at text
);
create index if not exists join_codes_teacher on join_codes (teacher_id);

create table if not exists learner_links (
    learner_account_id text primary key references accounts(id) on delete cascade,
    teacher_id text not null references accounts(id) on delete cascade,
    class_id text not null,
    class_name text not null,
    learner_profile_id text,
    learner_label text,
    joined_at text not null
);
create index if not exists learner_links_teacher on learner_links (teacher_id);

create table if not exists picture_logins (
    account_id text primary key references accounts(id) on delete cascade,
    teacher_id text not null,
    class_id text not null,
    learner_profile_id text not null,
    picture_hash text not null,
    failed_attempts integer not null default 0,
    locked_until text,
    created_at text not null,
    unique (teacher_id, learner_profile_id)
);

create table if not exists password_resets (
    token_hash text primary key,
    account_id text not null references accounts(id) on delete cascade,
    expires_at text not null,
    used_at text
);

-- ---------------------------------------------------------------- agent runs, events and feedback memory

create table if not exists runs (
    id text primary key,
    kind text not null,
    status text not null,
    title text not null,
    created_at text not null,
    finished_at text,
    parent_run_id text,
    lesson_id text,
    model text,
    request_json text not null,
    result_json text,
    error text,
    approved_at text,
    owner_id text,
    class_id text
);
create index if not exists runs_owner on runs (owner_id, created_at);

create table if not exists events (
    run_id text not null,
    seq integer not null,
    event_json text not null,
    primary key (run_id, seq)
);

create table if not exists feedback (
    id bigint generated by default as identity primary key,
    created_at text not null,
    lesson_id text,
    run_id text,
    grade text,
    subject text,
    topic text,
    learner_id text not null,
    learner_label text,
    adaptation_id text,
    strategy text,
    instruction text,
    outcome text not null,
    note text,
    teacher_id text
);
create index if not exists feedback_learner on feedback (learner_id);

-- ---------------------------------------------------------------- the teacher's workspace and materials

create table if not exists workspace_docs (
    teacher_id text not null,
    kind text not null,                      -- classes | profiles | lessons
    id text not null,
    class_id text,
    body text not null,                      -- the record as JSON
    updated_at text not null,
    created_at text,
    primary key (teacher_id, kind, id)
);
create index if not exists workspace_class on workspace_docs (teacher_id, kind, class_id);

create table if not exists resources (
    id text primary key,
    teacher_id text not null,
    title text not null,
    grade text not null,
    subject text not null,
    type text not null,
    topic text not null,
    filename text not null,
    mime text not null,
    size integer not null,
    text text not null,                      -- text read from the file, used when planning
    data bytea not null,                     -- the file itself (up to 10 MB)
    created_at text not null
);
create index if not exists resources_teacher on resources (teacher_id, created_at);

-- ---------------------------------------------------------------- what learners do with approved lessons

create table if not exists learner_activity (
    id bigint generated by default as identity primary key,
    created_at text not null,
    learner_account_id text not null,
    teacher_id text not null,
    class_id text not null,
    learner_profile_id text,
    run_id text not null,
    kind text not null,                      -- opened | answer | practice_done | reflection | explain
    data text not null
);
create index if not exists activity_class on learner_activity (teacher_id, class_id, run_id);
create index if not exists activity_learner on learner_activity (learner_account_id);

-- ---------------------------------------------------------------- only the backend may read or write

alter table accounts enable row level security;
alter table auth_sessions enable row level security;
alter table join_codes enable row level security;
alter table learner_links enable row level security;
alter table picture_logins enable row level security;
alter table password_resets enable row level security;
alter table runs enable row level security;
alter table events enable row level security;
alter table feedback enable row level security;
alter table workspace_docs enable row level security;
alter table resources enable row level security;
alter table learner_activity enable row level security;
