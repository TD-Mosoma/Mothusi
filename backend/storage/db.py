"""One database for every store.

Locally (and in tests) Mothusi uses a SQLite file. In production it uses PostgreSQL, for example Supabase, when
MOTHUSI_DATABASE_URL is set. Stores write portable SQL with `?` placeholders; the few differences between the two
databases are handled here:

- placeholders: `?` becomes `%s` for PostgreSQL;
- schema types: `{ID}` (an auto-numbered primary key) and `{BLOB}` (binary data) in CREATE TABLE statements;
- adding a column to an existing table (`add_column`).
"""

import os
import re
import sqlite3
import threading
from contextlib import contextmanager
from pathlib import Path
from typing import Any, Iterator

try:  # PostgreSQL support is only needed when a database URL is configured.
    import psycopg
    from psycopg.rows import dict_row
    from psycopg_pool import ConnectionPool
except ImportError:  # pragma: no cover - psycopg is a declared dependency
    psycopg = None

SCHEMA_TYPES = {
    "sqlite": {"{ID}": "INTEGER PRIMARY KEY AUTOINCREMENT", "{BLOB}": "BLOB"},
    "postgres": {"{ID}": "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "{BLOB}": "BYTEA"},
}
IntegrityErrors: tuple[type[Exception], ...] = (sqlite3.IntegrityError,) + ((psycopg.IntegrityError,) if psycopg else ())


def is_postgres_url(target: str | Path) -> bool:
    return str(target).startswith(("postgres://", "postgresql://"))


class Tx:
    """A transaction: run statements and read rows as dicts."""

    def __init__(self, cursor: Any, dialect: str):
        self._cur = cursor
        self.dialect = dialect

    def _sql(self, sql: str) -> str:
        return sql.replace("%", "%%").replace("?", "%s") if self.dialect == "postgres" else sql

    def execute(self, sql: str, params: tuple | list = ()) -> "Tx":
        self._cur.execute(self._sql(sql), tuple(params))
        return self

    def executemany(self, sql: str, rows: list[tuple]) -> "Tx":
        if rows:
            self._cur.executemany(self._sql(sql), rows)
        return self

    def one(self, sql: str, params: tuple | list = ()) -> dict[str, Any] | None:
        row = self.execute(sql, params)._cur.fetchone()
        return dict(row) if row is not None else None

    def all(self, sql: str, params: tuple | list = ()) -> list[dict[str, Any]]:
        return [dict(r) for r in self.execute(sql, params)._cur.fetchall()]

    @property
    def rowcount(self) -> int:
        return self._cur.rowcount


class Database:
    def __init__(self, target: str | Path, pool_max: int = 10):
        self.target = str(target)
        if is_postgres_url(target):
            if psycopg is None:
                raise RuntimeError("PostgreSQL needs the psycopg package: uv add 'psycopg[binary]' psycopg-pool")
            self.dialect = "postgres"
            # prepare_threshold=None keeps it working through Supabase's transaction pooler as well.
            # Small pools on serverless hosts: many instances may each hold one.
            # Supabase's pooler closes idle connections, so check each one before use and recycle old ones.
            self._pool = ConnectionPool(self.target, min_size=1, max_size=max(1, pool_max), open=True, timeout=30,
                                        check=ConnectionPool.check_connection, max_idle=120, max_lifetime=900,
                                        kwargs={"prepare_threshold": None, "row_factory": dict_row})
        else:
            self.dialect = "sqlite"
            Path(self.target).parent.mkdir(parents=True, exist_ok=True)
            self._lock = threading.RLock()
            self._conn = sqlite3.connect(self.target, check_same_thread=False)
            self._conn.row_factory = sqlite3.Row
            self._conn.execute("PRAGMA foreign_keys = ON")
            self._conn.execute("PRAGMA journal_mode = WAL")

    @contextmanager
    def tx(self) -> Iterator[Tx]:
        """One transaction: committed when the block ends, rolled back if it raises."""
        if self.dialect == "postgres":
            with self._pool.connection() as conn, conn.transaction(), conn.cursor() as cur:
                yield Tx(cur, "postgres")
        else:
            with self._lock, self._conn:
                yield Tx(self._conn.cursor(), "sqlite")

    def one(self, sql: str, params: tuple | list = ()) -> dict[str, Any] | None:
        with self.tx() as t:
            return t.one(sql, params)

    def all(self, sql: str, params: tuple | list = ()) -> list[dict[str, Any]]:
        with self.tx() as t:
            return t.all(sql, params)

    def run(self, sql: str, params: tuple | list = ()) -> int:
        with self.tx() as t:
            return t.execute(sql, params).rowcount

    def create(self, schema: str) -> None:
        """Run CREATE TABLE / CREATE INDEX statements, with the types this database uses."""
        for token, value in SCHEMA_TYPES[self.dialect].items():
            schema = schema.replace(token, value)
        statements = [s.strip() for s in schema.split(";") if s.strip()]
        with self.tx() as t:
            for statement in statements:
                t.execute(statement)
            if self.dialect == "postgres":
                # Supabase exposes the public schema through its API. Row-level security with no policies
                # means only the server (which connects as the table owner) can read or write these tables.
                for table in re.findall(r"CREATE TABLE IF NOT EXISTS (\w+)", schema):
                    t.execute(f"ALTER TABLE {table} ENABLE ROW LEVEL SECURITY")

    def add_column(self, table: str, column: str) -> None:
        """Add a column that a later version introduced, if the table does not have it yet."""
        with self.tx() as t:
            if self.dialect == "postgres":
                t.execute(f"ALTER TABLE {table} ADD COLUMN IF NOT EXISTS {column}")
            else:
                existing = {r["name"] for r in t.all(f"PRAGMA table_info({table})")}
                if column.split()[0] not in existing:
                    t.execute(f"ALTER TABLE {table} ADD COLUMN {column}")

    def close(self) -> None:
        if self.dialect == "postgres":
            self._pool.close()
        else:
            self._conn.close()


_shared: dict[str, Database] = {}
_shared_lock = threading.Lock()


def connect(target: str | Path, pool_max: int | None = None) -> Database:
    """The one Database for a target, shared by every store in the process."""
    key = str(target)
    with _shared_lock:
        if key not in _shared:
            if pool_max is None:
                pool_max = int(os.getenv("MOTHUSI_DB_POOL_MAX", "3" if os.getenv("VERCEL") else "10"))
            _shared[key] = Database(target, pool_max)
        return _shared[key]
